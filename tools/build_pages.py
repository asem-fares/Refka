#!/usr/bin/env python3
"""Refka website: write the text into the HTML that search engines read before JavaScript runs.

  python3 tools/build_pages.py

1. index.html  gets the English text from assets/js/i18n/en.js (title, description, every data-i18n element).
2. ar/index.html is written from index.html with the Arabic text from assets/js/i18n/ar.js, right-to-left,
   with its own address, title and description, so Google can index Arabic as its own page.
The browser still runs app.js on both pages; this only makes the first, script-free view complete.
Runs in the deploy workflow before every publish, so the Arabic page can never fall behind.
"""
import html, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = 'https://refka.tech'


def load(lang):
    t = open(os.path.join(ROOT, 'assets/js/i18n/%s.js' % lang), encoding='utf-8').read()
    return {k: json.loads(v) for k, v in re.findall(r'^  ([A-Za-z0-9_]+): (".*?"),?$', t, re.M)}


EL = re.compile(r'<(\w+)\b([^>]*?)\b(data-i18n(?:-html)?)="([^"]+)"([^>]*)>(.*?)</\1>', re.S)


def fill(s, T, fallback):
    def rep(m):
        tag, attr, key = m.group(1), m.group(3), m.group(4)
        v = T.get(key, fallback.get(key))
        if v is None:
            return m.group(0)
        if attr == 'data-i18n':
            v = html.escape(v, quote=False)
        if 'data-one-line' in m.group(2) + m.group(5):
            v = re.sub(r'<br\s*/?>', ' ', v)
        return m.group(0)[:m.start(6) - m.start(0)] + v + '</%s>' % tag
    s = EL.sub(rep, s)
    s = re.sub(r'(aria-label=")[^"]*("[^>]*data-i18n-aria="([^"]+)")', lambda m: m.group(1) + html.escape(T.get(m.group(3), fallback.get(m.group(3), ''))) + m.group(2), s)
    return s


def meta(s, T, url, locale, share_title):
    e = lambda x: html.escape(x)
    s = re.sub(r'<title>.*?</title>', '<title>%s</title>' % e(T['pageTitle']), s, count=1)
    for sel in ('name="description"', 'property="og:description"', 'name="twitter:description"'):
        s = re.sub(r'(<meta %s content=")[^"]*"' % re.escape(sel), lambda m: m.group(1) + e(T['metaDesc']) + '"', s)
    for sel in ('property="og:title"', 'name="twitter:title"'):
        s = re.sub(r'(<meta %s content=")[^"]*"' % re.escape(sel), lambda m: m.group(1) + e(share_title) + '"', s)
    s = re.sub(r'(<meta property="og:url" content=")[^"]*"', lambda m: m.group(1) + url + '"', s)
    s = re.sub(r'(<meta property="og:locale" content=")[^"]*"', lambda m: m.group(1) + locale + '"', s)
    s = re.sub(r'(<link rel="canonical" href=")[^"]*"', lambda m: m.group(1) + url + '"', s)
    return s


def faq_ld(s, T):
    def rep(m):
        d = json.loads(m.group(1))
        if d.get('@type') != 'FAQPage':
            return m.group(0)
        d['mainEntity'] = [{"@type": "Question", "name": T['faq_q%d' % n],
                            "acceptedAnswer": {"@type": "Answer", "text": T['faq_a%d' % n]}} for n in range(1, 8)]
        return '<script type="application/ld+json">\n' + json.dumps(d, ensure_ascii=False, indent=2) + '\n</script>'
    return re.sub(r'<script type="application/ld\+json">(.*?)</script>', rep, s, flags=re.S)


en, ar = load('en'), load('ar')
src = open(os.path.join(ROOT, 'index.html'), encoding='utf-8').read()

# Cache busting: every script and stylesheet URL carries ?v=<hash of all JS and CSS>, so after a deploy
# no visitor mixes a new page with yesterday's cached script (GitHub Pages caches files for 10 minutes).
import glob, hashlib
_h = hashlib.sha1()
for p in sorted(glob.glob(os.path.join(ROOT, 'assets/js/**/*.js'), recursive=True) + glob.glob(os.path.join(ROOT, 'assets/css/*.css'))):
    _h.update(open(p, 'rb').read())
VER = _h.hexdigest()[:10]
src = re.sub(r'((?:src|href)="/assets/(?:js|css)/[^"?]+\.(?:js|css))(?:\?v=[0-9a-f]+)?"', lambda m: m.group(1) + '?v=' + VER + '"', src)

page = faq_ld(meta(fill(src, en, en), en, SITE + '/', 'en_US', 'Refka | At your gym, nobody trains alone.'), en)
open(os.path.join(ROOT, 'index.html'), 'w', encoding='utf-8').write(page)

a = fill(page, ar, en)
a = re.sub(r'<html\b[^>]*>', '<html lang="ar" dir="rtl">', a, count=1)
a = meta(a, ar, SITE + '/ar/', 'ar_EG', 'Refka | في جيمك، لا أحد يتمرّن وحده.')
a = faq_ld(a, ar)
a = a.replace('<!-- ', '<!-- Generated by tools/build_pages.py from index.html: edit index.html and ar.js, not this file. -->\n<!-- ', 1) if '<!-- Generated' not in a else a
os.makedirs(os.path.join(ROOT, 'ar'), exist_ok=True)
open(os.path.join(ROOT, 'ar', 'index.html'), 'w', encoding='utf-8').write(a)
print('index.html (en) and ar/index.html (ar) written')
