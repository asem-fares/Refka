#!/usr/bin/env bash
# Rebuilds supabase/deploy.sql from supabase/migrations/*.sql (in name order). Run after any migration change;
# supabase/tests/run.js fails if deploy.sql is out of date.
set -euo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="$DIR/deploy.sql"
{
  echo "-- Refka v1: every migration in one file, for the Supabase SQL editor on a fresh project."
  echo "-- GENERATED by supabase/build-deploy.sh from supabase/migrations/. Do not edit by hand."
  echo "-- Safe to run again: tables use \"if not exists\", functions \"create or replace\", grants are re-applied."
  echo "-- Needs only what Supabase provides: auth.users, auth.uid(), auth.jwt(), roles anon/authenticated,"
  echo "-- and pgcrypto in schema extensions (created below if missing)."
  echo
  echo "begin;"
  for f in $(ls "$DIR"/migrations/*.sql | sort); do
    echo
    echo "-- ==================================================================== $(basename "$f")"
    cat "$f"
  done
  echo
  echo "commit;"
} > "$OUT"
echo "wrote $OUT"
